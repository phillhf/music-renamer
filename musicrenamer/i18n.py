def t(text, **values):
    translated = EN.get(text, text) if language == "en" else text
    return translated.format(**values) if values else translated


def format_duration(seconds):
    if seconds < 60:
        return t("{seconds} Sek.", seconds=round(seconds))
    if seconds < 3600:
        return t("{minutes} Min.", minutes=round(seconds / 60))
    return t("{hours} Std. {minutes} Min.", hours=int(seconds // 3600), minutes=round(seconds % 3600 / 60))
